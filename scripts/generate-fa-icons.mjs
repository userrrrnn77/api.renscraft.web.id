// scripts/generate-fa-icons.mjs

// Generates src/services/contract/faIcons.ts: the Font Awesome Free class names
// that really exist per style (solid / regular / brands), plus FA's own search
// terms per icon (used to pick a replacement when the model invents a name such
// as "fa-coffee-beans").
//
// The preview loads Font Awesome from cdnjs (client/src/utils/sandpackUtils.js,
// currently 6.4.0). When that version changes:
//
//   npm i -D @fortawesome/fontawesome-free@<same version>
//   node scripts/generate-fa-icons.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const metaPath =
  process.argv[2] ||
  path.join(
    root,
    "node_modules/@fortawesome/fontawesome-free/metadata/icon-families.json",
  );
const outPath =
  process.argv[3] || path.join(root, "src/services/contract/faIcons.ts");
const pkgPath = path.join(path.dirname(metaPath), "..", "package.json");

const meta = JSON.parse(fs.readFileSync(metaPath, "utf8"));
const version = fs.existsSync(pkgPath)
  ? JSON.parse(fs.readFileSync(pkgPath, "utf8")).version
  : "unknown";

const solid = [];
const regular = [];
const brands = [];
const terms = {};

for (const [name, icon] of Object.entries(meta)) {
  const styles = icon.svgs?.classic ?? {};
  // every name that works as a CSS class: the icon itself + its aliases
  // ("coffee" is an alias of "mug-saucer")
  const names = [name, ...(icon.aliases?.names ?? [])];
  for (const n of names) {
    if (styles.solid) solid.push(n);
    if (styles.regular) regular.push(n);
    if (styles.brands) brands.push(n);
  }
  const words = new Set(
    [name, ...(icon.search?.terms ?? [])]
      .flatMap((x) => String(x).toLowerCase().split(/[^a-z0-9]+/))
      .filter((w) => w.length > 1),
  );
  if (words.size > 0) terms[name] = [...words].sort();
}

const uniq = (l) => JSON.stringify([...new Set(l)].sort());

const out = `// AUTO-GENERATED by scripts/generate-fa-icons.mjs. Do not edit by hand.
// Source: @fortawesome/fontawesome-free ${version} (icon-families.json)

export const FA_VERSION = ${JSON.stringify(version)};

export const FA_SOLID: readonly string[] = ${uniq(solid)};

export const FA_REGULAR: readonly string[] = ${uniq(regular)};

export const FA_BRANDS: readonly string[] = ${uniq(brands)};

// icon name -> lowercase words from its name and FA's own search terms
export const FA_TERMS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(terms)};
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, out);
console.log(`FA ${version} -> ${path.relative(root, outPath)} (${Math.round(out.length / 1024)} KB)`);
